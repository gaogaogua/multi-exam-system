const dist = {};
let classified = 0;

for (const q of tm) {
  const ch = classify(q.title, q.analysis || '');
  // Set category to chapter (preserving type info as a suffix for filtering)
  q.category = ch;
  dist[ch] = (dist[ch] || 0) + 1;
  if (ch !== '综合/其他') classified++;
}

