function tokenize(text) {
  const cleaned = text.toLowerCase().replace(/[，。、；：""''！？（）《》【】\s,.!?;:'"()\[\]{}<>\/\\-]+/g, ' ');
  return cleaned.split(/\s+/).filter(w => w.length >= 1);
}

function classify(title, analysis) {
  const text = (title + ' ' + (analysis || '')).toLowerCase();
  const tokens = tokenize(text);

  let best = '未分类', bestScore = 0;
  for (const [ch, cfg] of Object.entries(CHAPTERS)) {
    let score = 0;
    for (const kw of cfg.keywords) {
      if (text.includes(kw)) score++;
    }
    if (score > bestScore) { bestScore = score; best = ch; }
  }
  return bestScore >= 1 ? best : '综合/其他';
}

