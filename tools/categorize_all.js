// 分类算法 (与 auto-categorizer.js 一致)
// ══════════════════════════════════════

function extractText(question) {
  const parts = [question.title || ''];
  if (question.options) {
    question.options.forEach(o => parts.push(typeof o === 'string' ? o : (o.text || '')));
  }
  if (question.analysis) parts.push(question.analysis);
  return parts.join(' ');
}

function tokenize(text) {
  const cleaned = text.toLowerCase().replace(/[，。、；：""''！？（）《》【】\s,.!?;:'"()\[\]{}<>\/\\-]+/g, ' ');
  const words = cleaned.split(/\s+/).filter(w => w.length >= 2);
  const chineseChars = text.replace(/[a-zA-Z0-9\s,.!?;:'"()\[\]{}<>\/\\-]+/g, '');
  return [...new Set(words.concat([...chineseChars]))];
}

function scoreCategory(tokens, keywords, baseWeight) {
  let score = 0;
  const matched = new Set();
  for (const token of tokens) {
    for (const kw of keywords) {
      if (matched.has(kw)) continue;
      if (token.includes(kw) || kw.includes(token)) {
        const matchQuality = Math.min(kw.length / token.length, token.length / kw.length);
        score += baseWeight * (0.5 + 0.5 * matchQuality);
        matched.add(kw);
      }
    }
  }
  return score / Math.max(1, Math.sqrt(tokens.length));
}

function classify(question, categories) {
  const text = extractText(question);
  const tokens = tokenize(text);
  if (tokens.length === 0) return '未分类';

  let bestCat = '未分类';
  let bestScore = 0;

  for (const [cat, config] of Object.entries(categories)) {
    const s = scoreCategory(tokens, config.keywords, config.weight);
    if (s > bestScore) { bestScore = s; bestCat = cat; }
  }

  return bestScore >= 0.12 ? bestCat : '未分类';
}

